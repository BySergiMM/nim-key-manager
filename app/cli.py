"""``nimkm`` -- an MCP server for the API keys of your own NVIDIA Build/NIM account.

The primary surface is ``nimkm mcp serve``: an MCP client spawns it and talks
JSON-RPC over stdio. ``nimkm mcp setup`` registers that command with the clients
found on this machine. The web dashboard (``nimkm web``) is a separate,
optional administration surface over the same database.

Design notes
------------
* **stdlib only.** The CLI must be able to report a broken installation, so it
  never depends on anything that could itself be broken. Heavy imports (uvicorn,
  SQLAlchemy, the application package) happen inside the commands that need them.
* **Settings are read lazily.** ``app.core.config`` is imported only *after*
  ``config.env`` has been written and after the stdio profile has been applied,
  because instantiating ``Settings`` also builds the database engine downstream.
* **Nothing leaks.** No user-facing string mentions Python, uv, uvicorn or
  FastAPI: from the outside this is one command that speaks MCP.
* **Idempotent.** ``nimkm init`` never overwrites existing secrets unless asked;
  ``nimkm mcp setup`` can be re-run at any time.
"""

