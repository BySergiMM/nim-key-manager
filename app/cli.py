def cmd_init(args: argparse.Namespace) -> int:
    home = paths.ensure_dirs()
    config_path = paths.config_file()
    existing = read_config(config_path)

    preserved_master_key: str | None = None
    if existing and args.force:
        backup = config_path.with_suffix(".env.bak")
        shutil.copy2(config_path, backup)
        warn(f"existing configuration backed up to {backup}")
        # Regenerating ENCRYPTION_MASTER_KEY would make every stored API key
        # undecryptable, so it is carried over. There is no safe way to rotate
        # it without re-encrypting the database first.
        preserved_master_key = existing.get("ENCRYPTION_MASTER_KEY") or None
        existing = {}

    if existing:
        step(f"configuration already present at {config_path}")
        values = existing
        host = values.get("HOST", "127.0.0.1")
        port = int(values.get("PORT", "8000"))
    else:
        host = args.host
        port = args.port
        database_url = args.database_url or paths.default_database_url()
        values = _default_config(database_url, host, port)
        if preserved_master_key:
            values["ENCRYPTION_MASTER_KEY"] = preserved_master_key
            say(dim("  keeping the existing ENCRYPTION_MASTER_KEY so stored keys stay readable"))
        write_config(values, config_path)
        ok(f"generated secrets and configuration at {config_path}")

    if args.database_url and values.get("DATABASE_URL") != args.database_url:
        values["DATABASE_URL"] = args.database_url
        write_config(values, config_path)
        ok("database URL updated")

    # Only now is it safe to import anything that reads Settings.
    step("applying database migrations")
    from app.infrastructure.db import migrations

    migrations.upgrade()
    ok(f"database ready ({_describe_database()})")

    created = _ensure_admin(args)
    say()
    say(bold("NIM Key Manager is ready."))
    say(f"  home       {home}")
    say(f"  dashboard  {_browsable_url(host, port)}  {dim('(nimkm web)')}")
    if created:
        email, password = created
        say(f"  admin      {email}")
        if password:
            say(f"  password   {bold(password)}  {dim('(shown once)')}")
    if not args.quiet_next_step:
        say()
        say(f"Connect it to your MCP client with {bold('nimkm mcp setup')}.")
    return 0


def _describe_database() -> str:
    from app.core.config import get_settings

    url = get_settings().database_url
    sqlite_file = paths.sqlite_path(url)
    return f"sqlite {sqlite_file}" if sqlite_file else url.split("@")[-1]


def _ensure_admin(args: argparse.Namespace) -> tuple[str, str | None] | None:
    """Create the first administrator when the user table is empty."""
    from app.application.services.auth_service import AuthService
    from app.domain.enums import Role
    from app.infrastructure.db.repositories import UserRepository
    from app.infrastructure.db.session import SessionFactory

    async def _create() -> tuple[str, str | None] | None:
        async with SessionFactory() as session:
            if await UserRepository(session).count() > 0:
                return None
            email = args.admin_email
            password = args.admin_password
            generated = False
            if not email:
                prompt = f"Administrator e-mail [{DEFAULT_ADMIN_EMAIL}]: "
                answer = None if args.no_input else _ask(prompt)
                email = (answer or "").strip() or DEFAULT_ADMIN_EMAIL
            _require_valid_email(email)
            if not password:
                if not args.no_input and _interactive():
                    with contextlib.suppress(EOFError, KeyboardInterrupt):
                        password = getpass.getpass("Password (empty to generate): ").strip()
                if not password:
                    password = secrets.token_urlsafe(18)
                    generated = True
            await AuthService(session).register(
                email=email, password=password, full_name="Administrator",
                role=Role.ADMIN, actor=None,
            )
            return email, password if generated else None

    return _run_async(_create())


def _require_valid_email(email: str) -> None:
    """Reject an address the API and MCP layers would later refuse to serialise.

    Accounts created here bypass the request schemas, so an address like
    ``admin@localhost`` is accepted at creation and then breaks every response
    that contains the user. Fail here, where it is one clear message.
    """
    from pydantic import BaseModel, EmailStr, ValidationError

    class _Probe(BaseModel):
        email: EmailStr

    try:
        _Probe(email=email)
    except ValidationError as exc:
        reason = exc.errors()[0].get("ctx", {}).get("reason", "not a valid address")
        raise SystemExit(
            f"{red('XX')}  {email!r} cannot be used: {reason}\n"
            f"    Try something like {DEFAULT_ADMIN_EMAIL} or your real address."
        ) from exc


def _startup_blocker(settings: Any) -> str | None:
    """Reason this instance cannot serve, or ``None`` when it is viable.

    A container gets everything from the environment and has no ``config.env``;
    only a machine with *neither* a config file *nor* real secrets is unusable.
    """
    if paths.config_file().exists() or not settings.insecure_defaults():
        return None
    return "no configuration found -- run 'nimkm init' first (or 'nimkm up')."


def cmd_serve(args: argparse.Namespace) -> int:
    from app.core.config import get_settings

    settings = get_settings()
    blocker = _startup_blocker(settings)
    if blocker:
        fail(blocker)
        return 1
    host = args.host or settings.host
    port = args.port or settings.port

    if not _port_is_free(host, port):
        fail(f"port {port} is already in use. Try 'nimkm web --port {port + 1}'.")
        return 1

    import uvicorn

    # ASCII only: Windows consoles default to a legacy code page.
    say(f"{bold('NIM Key Manager')} {__version__}  ->  {cyan(_browsable_url(host, port))}")
    say(dim("dashboard /  |  API docs /docs  |  health /health  |  Ctrl-C to stop"))
    uvicorn.run(
        "app.main:create_asgi_app",
        factory=True,
        host=host,
        port=port,
        reload=args.reload,
        proxy_headers=args.proxy_headers,
        forwarded_allow_ips="*" if args.proxy_headers else None,
        log_config=None,
    )
    return 0


def cmd_up(args: argparse.Namespace) -> int:
    if not paths.config_file().exists():
        init_args = argparse.Namespace(
            force=False, host=args.host or "127.0.0.1", port=args.port or 8000,
            database_url=None, admin_email=None, admin_password=None,
            no_input=args.no_input, quiet_next_step=True,
        )
        code = cmd_init(init_args)
        if code != 0:
            return code
        say()
    else:
        from app.infrastructure.db import migrations

        migrations.upgrade()

    from app.core.config import get_settings

    settings = get_settings()
    host = args.host or settings.host
    port = args.port or settings.port
    if not _port_is_free(host, port):
        new_port = _first_free_port(host, port + 1)
        warn(f"port {port} busy -- using {new_port} instead")
        port = new_port

    if not args.no_browser:
        url = _browsable_url(host, port)
        threading.Timer(1.5, lambda: webbrowser.open(url)).start()

    serve_args = argparse.Namespace(
        host=host, port=port, reload=False, proxy_headers=False
    )
    return cmd_serve(serve_args)


def cmd_migrate(args: argparse.Namespace) -> int:
    from app.infrastructure.db import migrations

    if args.revision == "head":
        migrations.upgrade()
    elif args.downgrade:
        migrations.downgrade(args.revision)
    else:
        migrations.upgrade(args.revision)
    ok(f"database at revision {migrations.head_revision()}")
    return 0


def cmd_doctor(args: argparse.Namespace) -> int:
    checks: list[tuple[str, str, str]] = []  # (level, subject, detail)

    def add(level: str, subject: str, detail: str = "") -> None:
        checks.append((level, subject, detail))

    version = ".".join(str(p) for p in sys.version_info[:3])
    add("ok" if sys.version_info >= (3, 10) else "fail", f"runtime {version}", str(paths.home()))

    _add_client_checks(add)

    config_path = paths.config_file()
    if config_path.exists():
        add("ok", "configuration", str(config_path))
        if os.name != "nt":
            mode = config_path.stat().st_mode & 0o777
            add(
                "ok" if mode == 0o600 else "warn",
                f"config permissions {mode:o}",
                "" if mode == 0o600 else "expected 600; run: chmod 600 " + str(config_path),
            )
    else:
        add("fail", "configuration missing", "run 'nimkm init'")
        _report(checks)
        return 1

    from app.core.config import get_settings

    settings = get_settings()
    insecure = settings.insecure_defaults()
    add(
        "fail" if insecure else "ok",
        "secrets",
        f"{', '.join(insecure)} still using the development placeholder" if insecure else
        "JWT_SECRET and ENCRYPTION_MASTER_KEY are set",
    )

    from app.infrastructure.db import migrations

    try:
        current = _run_async(migrations.current_revision())
        head = migrations.head_revision()
        if current is None:
            add("fail", "database", "reachable but not migrated -- run 'nimkm migrate'")
        elif current != head:
            add("warn", "database", f"at {current}, latest is {head} -- run 'nimkm migrate'")
        else:
            add("ok", "database", f"{_describe_database()} (revision {current})")
    except Exception as exc:  # noqa: BLE001 - diagnostics must not crash
        add("fail", "database unreachable", str(exc).splitlines()[0])

    try:
        from app.infrastructure.db.repositories import UserRepository
        from app.infrastructure.db.session import SessionFactory

        async def _count() -> int:
            async with SessionFactory() as session:
                return await UserRepository(session).count()

        users = _run_async(_count())
        add("ok" if users else "warn", f"{users} user(s)", "" if users else "run 'nimkm init'")
    except Exception as exc:  # noqa: BLE001
        add("warn", "users", str(exc).splitlines()[0])

    free = _port_is_free(settings.host, settings.port)
    add("ok" if free else "warn", f"port {settings.port}",
        "available" if free else "in use (an instance may already be running)")

    # The remote connector is optional; a local-only install is complete without it.
    if not settings.mcp_enabled:
        add("ok", "remote connector", "disabled")
    elif settings.mcp_credentials_configured():
        add("ok", "remote connector", f"{settings.mcp_auth_provider} OAuth configured")
        if not settings.mcp_allowed_identities:
            add("warn", "MCP allow-list empty", "nobody can connect; set MCP_ALLOWED_IDENTITIES")
    else:
        add("ok", "remote connector", "not configured (only needed for remote clients)")

    if not args.offline:
        try:
            request = urllib.request.Request(settings.nvidia_validation_url)
            urllib.request.urlopen(request, timeout=6)  # noqa: S310
            add("ok", "NVIDIA endpoint reachable", settings.nvidia_validation_url)
        except urllib.error.HTTPError as exc:
            level = "ok" if exc.code in (401, 403) else "warn"
            add(level, "NVIDIA endpoint reachable", f"HTTP {exc.code} (auth expected)")
        except Exception as exc:  # noqa: BLE001
            add("warn", "NVIDIA endpoint unreachable", str(exc).splitlines()[0])

    return _report(checks)


def _add_client_checks(add: Any) -> None:
    """Where the MCP server is registered -- the first thing that breaks."""
    from app.mcp import clients

    launcher = _launcher_or_none()
    if launcher is None:
        add("fail", "launcher missing", "reinstall: clients have nothing to run")

    registered: list[tuple[Any, dict[str, Any]]] = []
    for target in clients.discover_targets():
        entry, error = _registration_or_error(target, clients.DEFAULT_SERVER_NAME)
        if error:
            add("warn", f"unreadable client config: {target.label}", error)
        elif entry is not None:
            registered.append((target, entry))

    if not registered:
        detected = [target.label for target in clients.detected_targets()]
        add(
            "warn", "MCP client",
            f"not registered ({', '.join(detected)} detected) -- run 'nimkm mcp setup'"
            if detected else "no MCP client found -- run 'nimkm mcp setup --print'",
        )
        return
    for target, entry in registered:
        stale = launcher is not None and entry.get("command") != launcher
        add(
            "warn" if stale else "ok",
            f"MCP client: {target.label}",
            "points at another install -- run 'nimkm mcp setup'" if stale else str(target.path),
        )


def _report(checks: list[tuple[str, str, str]]) -> int:
    say(bold(f"nimkm {__version__}  |  {paths.home()}"))
    say()
    for level, subject, detail in checks:
        marker = {"ok": green("OK  "), "warn": yellow("WARN"), "fail": red("FAIL")}[level]
        say(f"  {marker}  {subject}{'  ' + dim(detail) if detail else ''}")
    failures = sum(1 for level, _, _ in checks if level == "fail")
    warnings = sum(1 for level, _, _ in checks if level == "warn")
    say()
    if failures:
        say(red(f"{failures} problem(s) need attention."))
        return 1
    say(green("Everything looks good.") if not warnings else yellow(f"{warnings} warning(s)."))
    return 0


