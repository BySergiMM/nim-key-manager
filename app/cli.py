def cmd_config(args: argparse.Namespace) -> int:
    path = paths.config_file()
    if args.action == "path":
        say(str(path))
        return 0
    if not path.exists():
        fail("no configuration found -- run 'nimkm init' first.")
        return 1
    if args.action == "show":
        values = read_config(path)
        secretish = ("SECRET", "KEY", "PASSWORD", "TOKEN")
        for key, value in values.items():
            masked = value
            if any(word in key for word in secretish) and value:
                masked = value[:4] + "..." + dim("(hidden)")
            say(f"{key}={masked}")
        return 0
    if args.action == "edit":
        editor = os.environ.get("EDITOR") or ("notepad" if os.name == "nt" else "nano")
        return subprocess.call([editor, str(path)])
    # set
    values = read_config(path)
    for assignment in args.assignments:
        if "=" not in assignment:
            fail(f"expected KEY=VALUE, got {assignment!r}")
            return 1
        key, _, value = assignment.partition("=")
        values[key.strip().upper()] = value.strip()
    write_config(values, path)
    ok(f"updated {len(args.assignments)} setting(s) in {path}")
    say(dim("restart the server for changes to take effect"))
    return 0


def cmd_admin(args: argparse.Namespace) -> int:
    from app.application.services.auth_service import AuthService
    from app.core.security import hash_password
    from app.domain.enums import Role
    from app.infrastructure.db.repositories import UserRepository
    from app.infrastructure.db.session import SessionFactory

    async def _list() -> int:
        async with SessionFactory() as session:
            users = await UserRepository(session).list_all()
            if not users:
                warn("no users yet -- run 'nimkm init'")
                return 1
            for user in users:
                flag = "" if user.is_active else dim(" (inactive)")
                say(f"  {user.email:<40} {user.role}{flag}")
            return 0

    async def _create() -> int:
        _require_valid_email(args.email)
        password = args.password or secrets.token_urlsafe(18)
        async with SessionFactory() as session:
            actor = None
            if await UserRepository(session).count() > 0:
                actor = await UserRepository(session).get_by_email(args.actor or "")
                if actor is None or actor.role != Role.ADMIN.value:
                    fail("an existing administrator is required: pass --actor <admin-email>")
                    return 1
            await AuthService(session).register(
                email=args.email, password=password, full_name=args.name,
                role=Role(args.role), actor=actor,
            )
        ok(f"created {args.email} ({args.role})")
        if not args.password:
            say(f"  password  {bold(password)}  {dim('(shown once)')}")
        return 0

    async def _reset() -> int:
        password = args.password or secrets.token_urlsafe(18)
        async with SessionFactory() as session:
            repo = UserRepository(session)
            user = await repo.get_by_email(args.email)
            if user is None:
                fail(f"no user with e-mail {args.email}")
                return 1
            user.hashed_password = hash_password(password)
            await session.commit()
        ok(f"password updated for {args.email}")
        if not args.password:
            say(f"  password  {bold(password)}  {dim('(shown once)')}")
        return 0

    return _run_async({"list": _list, "create": _create, "reset-password": _reset}[args.action]())


