def _port_is_free(host: str, port: int) -> bool:
    probe_host = "127.0.0.1" if host in ("0.0.0.0", "::") else host
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.settimeout(0.6)
        return sock.connect_ex((probe_host, port)) != 0


def _first_free_port(host: str, port: int, attempts: int = 20) -> int:
    for candidate in range(port, port + attempts):
        if _port_is_free(host, candidate):
            return candidate
    return port


def _browsable_url(host: str, port: int) -> str:
    return f"http://{'127.0.0.1' if host in ('0.0.0.0', '::') else host}:{port}"


def _interactive() -> bool:
    return sys.stdin is not None and sys.stdin.isatty()


def _ask(prompt: str) -> str | None:
    """Read a line, or ``None`` when there is nobody to answer.

    ``isatty()`` is not proof that a read will succeed: a console handle
    inherited from a parent that has already closed its input raises EOFError.
    Prompts must degrade to "no answer", never crash the command.
    """
    if not _interactive():
        return None
    try:
        return input(prompt)
    except (EOFError, KeyboardInterrupt):
        say()
        return None


def _run_async(coro: Any) -> Any:
    import asyncio

    if sys.platform == "win32":  # psycopg/asyncpg need the selector loop on Windows
        asyncio.set_event_loop_policy(asyncio.WindowsSelectorEventLoopPolicy())
    return asyncio.run(coro)


def _http_json(url: str, timeout: float = 6.0) -> Any:
    request = urllib.request.Request(url, headers={"Accept": "application/json"})
    with urllib.request.urlopen(request, timeout=timeout) as response:  # noqa: S310
        return json.loads(response.read().decode("utf-8"))


