def cmd_mcp_setup(args: argparse.Namespace) -> int:
    """Register this server with the MCP clients installed on this machine."""
    from app.mcp import clients

    name = args.name
    entry = clients.server_entry()

    if args.print_config:
        say(clients.snippet(name))
        return 0

    if args.scope:
        targets = [clients.target_by_key(args.scope)]
    else:
        targets = clients.detected_targets()
        if not targets:
            warn("no MCP client configuration found on this machine")
            say()
            say("Add this to your client's configuration file:")
            say()
            say(clients.snippet(name))
            say()
            say(dim("or re-run with --scope user|project|desktop to create the file"))
            return 1

    say(bold("Connect NIM Key Manager to your MCP client"))
    say()
    say(f"  command  {cyan(entry['command'])} {' '.join(entry['args'])}")
    say(f"  as       {bold(name)}")
    say()

    changed = 0
    already_connected = 0
    failures = 0
    for target in targets:
        try:
            existing = clients.registration(target, name)
        except clients.ClientConfigError as exc:
            fail(f"{target.label}: {exc}")
            failures += 1
            continue

        if existing == entry:
            ok(f"{target.label} {dim('already up to date')}")
            already_connected += 1
            continue

        say(f"{target.label}")
        say(dim(f"  {target.path}"))
        if existing is None:
            question = f"  Register '{name}' here?"
        else:
            # Do not silently discard a hand-edited entry: show what changes.
            say(dim(f"  currently: {existing.get('command', '?')}"))
            say(dim(f"  will be:   {entry['command']}"))
            question = f"  Replace the existing '{name}' entry?"
        if not _confirm(question, default=True, assume_yes=args.yes):
            say(dim("  skipped"))
            continue

        try:
            outcome = clients.register(target, entry, name)
            # Read it back: a write that "succeeded" but did not land is the one
            # failure the user would otherwise discover inside their AI client.
            if clients.registration(target, name) != entry:
                raise clients.ClientConfigError(
                    "the entry is not in the file after writing it; check "
                    f"{target.path} by hand"
                )
        except clients.ClientConfigError as exc:
            fail(f"  {exc}")
            failures += 1
            continue
        if outcome.backup:
            say(dim(f"  backup: {outcome.backup}"))
        ok(f"  registered  ({target.restart_hint})")
        changed += 1

    if changed:
        say()
        say(bold("Almost there:") + " restart your MCP client, then ask it")
        say(dim('  "list my NVIDIA keys"  or  "dispense a NIM key"'))
    if failures:
        return 1
    if not changed and not already_connected:
        # Nothing was connected -- the installer must keep advertising the step.
        return NOTHING_CHANGED
    return 0


def cmd_mcp_remove(args: argparse.Namespace) -> int:
    from app.mcp import clients

    targets = [clients.target_by_key(args.scope)] if args.scope else clients.detected_targets()
    removed = 0
    failures = 0
    for target in targets:
        try:
            if clients.registration(target, args.name) is None:
                continue
            if not _confirm(f"Remove '{args.name}' from {target.label}?", True, args.yes):
                continue
            outcome = clients.unregister(target, args.name)
        except clients.ClientConfigError as exc:
            fail(f"{target.label}: {exc}")
            failures += 1
            continue
        if outcome.backup:
            say(dim(f"  backup: {outcome.backup}"))
        ok(f"removed from {target.path}")
        removed += 1
    if failures:
        return 1
    if not removed:
        warn(f"'{args.name}' was not registered anywhere")
        return 1
    return 0


def _launcher_or_none() -> str | None:
    """The command clients should run, or ``None`` if it cannot be located."""
    from app.mcp import clients

    try:
        return clients.launcher()
    except clients.ClientConfigError:
        return None


def _registration_or_error(target: Any, name: str) -> tuple[dict[str, Any] | None, str | None]:
    """``(entry, error)`` -- a broken client config must not abort a read-only command."""
    from app.mcp import clients

    if not target.exists:
        return None, None
    try:
        return clients.registration(target, name), None
    except clients.ClientConfigError as exc:
        return None, str(exc)


def cmd_mcp_status(args: argparse.Namespace) -> int:
    from app.mcp import clients

    launcher = _launcher_or_none()
    say(bold("MCP server  ") + dim(f"{launcher} mcp serve" if launcher else "not found"))
    if launcher is None:
        warn("this installation has no launcher on disk; reinstall before registering")
    say()

    say(bold("Clients"))
    any_registered = False
    for target in clients.discover_targets():
        entry, error = _registration_or_error(target, args.name)
        if error:
            say(f"  {red('unreadable')}  {target.label}")
            say(dim(f"              {error}"))
        elif entry is not None:
            any_registered = True
            say(f"  {green('registered')}  {target.label}")
            say(dim(f"              {target.path}"))
            if launcher is not None and entry.get("command") != launcher:
                warn(f"  the registered command differs from this install: {entry.get('command')}")
                say(dim("  run 'nimkm mcp setup' to point it here"))
        elif target.exists:
            say(f"  {dim('detected  ')}  {target.label} {dim('(not registered)')}")
        else:
            say(f"  {dim('not found ')}  {target.label}")
    if not any_registered:
        say()
        say(dim("run 'nimkm mcp setup' to register with the detected clients"))

    from app.core.config import get_settings

    settings = get_settings()
    say()
    say(bold("Remote connector (optional)"))
    if not settings.mcp_enabled:
        say(f"  {dim('disabled')}")
    elif settings.mcp_credentials_configured():
        base = settings.resolve_public_base_url() or _browsable_url(settings.host, settings.port)
        say(f"  {green('configured')}  {base}{settings.mcp_mount_path}")
        say(f"  provider    {settings.mcp_auth_provider}")
        say(f"  allow-list  {', '.join(settings.mcp_allowed_identities) or red('empty')}")
    else:
        say(f"  {dim('idle')}  {dim('- only needed for remote clients (nimkm mcp oauth)')}")
    return 0 if any_registered else NOTHING_CHANGED


def cmd_mcp_oauth(args: argparse.Namespace) -> int:
    """Configure the OAuth-protected HTTP connector for *remote* clients."""
    from app.core.config import get_settings

    settings = get_settings()
    base = settings.resolve_public_base_url() or _browsable_url(settings.host, settings.port)
    values = read_config()
    if not values:
        fail("no configuration found -- run 'nimkm init' first.")
        return 1

    provider = args.provider or values.get("MCP_AUTH_PROVIDER", "github")
    say(bold(f"Remote connector over HTTPS ({provider} OAuth)"))
    say(dim("Local clients do not need this -- use 'nimkm mcp setup' instead."))
    say()
    say(f"1. Create an OAuth app at {cyan(_oauth_console(provider))}")
    say(f"2. Set the callback URL to {cyan(base + '/auth/callback')}")
    say("3. Paste the credentials below.")
    say()
    client_id = args.client_id or (_ask("Client ID: ") or "").strip()
    client_secret = args.client_secret or _ask_secret("Client secret: ")
    identities = args.allow or (_ask("Allowed identities (comma separated): ") or "").strip()
    if not (client_id and client_secret and identities):
        fail("client id, secret and at least one allowed identity are required")
        return 1

    values["MCP_AUTH_PROVIDER"] = provider
    values[f"MCP_{provider.upper()}_CLIENT_ID"] = client_id
    values[f"MCP_{provider.upper()}_CLIENT_SECRET"] = client_secret
    values["MCP_ALLOWED_IDENTITIES"] = identities
    write_config(values)
    say()
    ok("remote connector configured")
    say(f"  endpoint  {cyan(base + settings.mcp_mount_path)}")
    say(dim("  start it with 'nimkm web' and add the URL as a custom connector"))
    return 0


def _ask_secret(prompt: str) -> str:
    if not _interactive():
        return ""
    try:
        return getpass.getpass(prompt).strip()
    except (EOFError, KeyboardInterrupt):
        return ""


def _confirm(question: str, default: bool = True, assume_yes: bool = False) -> bool:
    if assume_yes:
        say(f"{question} {dim('yes')}")
        return True
    if not _interactive():
        say(f"{question} {dim('skipped (no terminal to ask on; use --yes)')}")
        return False
    suffix = "[Y/n]" if default else "[y/N]"
    answer = _ask(f"{question} {suffix} ")
    if answer is None:  # the prompt was shown but nobody could answer it
        say(dim("  no answer -- skipped (use --yes to accept unattended)"))
        return False
    answer = answer.strip().lower()
    if not answer:
        return default
    return answer in ("y", "yes")


def _oauth_console(provider: str) -> str:
    return {
        "github": "https://github.com/settings/developers",
        "google": "https://console.cloud.google.com/apis/credentials",
    }.get(provider, "the provider console")


def cmd_update(args: argparse.Namespace) -> int:
    spec = _resolve_latest_spec()
    if spec is None:
        fail("could not determine the latest version (no network?)")
        return 1
    version, source = spec
    if version == __version__ and not args.force:
        ok(f"already on the latest version ({__version__})")
        return 0

    managed = _managed_python()
    if managed is None:
        say(f"A newer version is available: {bold(version)} (current {__version__})")
        say()
        say("This copy was not installed by the official installer. Update it with:")
        say(f"  {bold('pip install --upgrade ' + PYPI_PACKAGE)}")
        say(f"  {dim('or re-run the installer from ' + DOCS_URL)}")
        return 0

    step(f"updating {__version__} -> {version}")
    result = subprocess.call(
        [str(managed), "-m", "pip", "install", "--upgrade", "-q", source]
    )
    if result != 0:
        fail("update failed")
        return result
    ok(f"updated to {version}. Run 'nimkm migrate' if the release adds migrations.")
    return 0


def _managed_python() -> Path | None:
    """Interpreter of the installer-managed virtualenv, if this is one."""
    venv = paths.runtime_dir() / "venv"
    candidate = venv / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
    if candidate.exists() and Path(sys.prefix).resolve() == venv.resolve():
        return candidate
    return None


#: Hosts an update may be downloaded from. The URL comes from an API response,
#: so it is treated as untrusted input: whatever it says, we only ever fetch
#: from these, and only over HTTPS.
_TRUSTED_DOWNLOAD_HOSTS = frozenset({"github.com", "objects.githubusercontent.com"})


def _is_trusted_download(url: str) -> bool:
    from urllib.parse import urlparse

    parsed = urlparse(url)
    return parsed.scheme == "https" and parsed.hostname in _TRUSTED_DOWNLOAD_HOSTS


def _resolve_latest_spec() -> tuple[str, str] | None:
    """Return ``(version, pip-installable-source)`` for the newest release."""
    try:
        release = _http_json(f"https://api.github.com/repos/{REPO}/releases/latest")
        version = str(release.get("tag_name", "")).lstrip("v")
        for asset in release.get("assets", []):
            name = asset.get("name", "")
            url = asset.get("browser_download_url", "")
            if name.endswith(".whl") and _is_trusted_download(url):
                return version, url
        if version:
            return version, f"{PYPI_PACKAGE}=={version}"
    except Exception:  # noqa: BLE001 - fall through to PyPI
        pass
    try:
        data = _http_json(f"https://pypi.org/pypi/{PYPI_PACKAGE}/json")
        return str(data["info"]["version"]), PYPI_PACKAGE
    except Exception:  # noqa: BLE001
        return None


def cmd_uninstall(args: argparse.Namespace) -> int:
    home = paths.home()
    say(bold("This will remove:"))
    say(f"  runtime  {paths.runtime_dir()}")
    say(f"  shims    {paths.bin_dir()}")
    if args.purge:
        say(f"  config   {paths.config_file()}")
        say(f"  data     {paths.data_dir()} {red('(your encrypted keys!)')}")
    else:
        say(dim(f"  keeping configuration and data in {home} (use --purge to delete)"))
    say()
    if not args.yes:
        if not _interactive():
            fail("refusing to uninstall non-interactively without --yes")
            return 1
        if input("Type 'yes' to continue: ").strip().lower() != "yes":
            say("aborted")
            return 1

    targets = [paths.bin_dir(), paths.runtime_dir()]
    if args.purge:
        targets += [paths.config_file(), paths.data_dir(), paths.logs_dir()]
    leftovers = []
    for target in targets:
        try:
            if target.is_dir():
                shutil.rmtree(target, ignore_errors=False)
            elif target.exists():
                target.unlink()
        except OSError:
            leftovers.append(target)

    if args.purge and not leftovers and home.exists():
        try:
            shutil.rmtree(home)
        except OSError:
            leftovers.append(home)

    if leftovers:
        warn("some files are still in use (you are running from inside them).")
        say("Close this process and delete manually:")
        for target in leftovers:
            say(f"  {target}")
    else:
        ok("uninstalled")
    say(dim("Remember to remove the PATH entry from your shell profile if you added one."))
    return 0


