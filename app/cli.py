CONFIG_HEADER = f"""\
# NIM Key Manager -- generated by `nimkm init`.
# Values here are defaults for this machine; real environment variables win.
# Full reference: https://github.com/{REPO}/blob/main/.env.example
"""


def read_config(path: Path | None = None) -> dict[str, str]:
    """Parse ``config.env`` into a mapping (comments and blanks ignored)."""
    path = path or paths.config_file()
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, _, value = stripped.partition("=")
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def write_config(values: dict[str, str], path: Path | None = None) -> Path:
    """Write ``config.env`` atomically with owner-only permissions."""
    path = path or paths.config_file()
    path.parent.mkdir(parents=True, exist_ok=True)
    body = CONFIG_HEADER + "\n" + "\n".join(f"{k}={v}" for k, v in values.items()) + "\n"
    tmp = path.with_suffix(".tmp")
    tmp.write_text(body, encoding="utf-8")
    if os.name != "nt":
        os.chmod(tmp, 0o600)
    tmp.replace(path)
    if os.name != "nt":
        os.chmod(path, 0o600)
    return path


def _new_secret() -> str:
    return secrets.token_urlsafe(48)


def _default_config(database_url: str, host: str, port: int) -> dict[str, str]:
    return {
        "ENVIRONMENT": "production",
        "DEBUG": "false",
        "HOST": host,
        "PORT": str(port),
        "DATABASE_URL": database_url,
        "AUTO_CREATE_TABLES": "false",
        "JWT_SECRET": _new_secret(),
        "ENCRYPTION_MASTER_KEY": _new_secret(),
        "MCP_OAUTH_JWT_SIGNING_KEY": _new_secret(),
        "PUBLIC_BASE_URL": f"http://{'127.0.0.1' if host in ('0.0.0.0', '::') else host}:{port}",
        # The connector stays idle until OAuth credentials are provided;
        # `nimkm mcp setup` fills these in.
        "MCP_ENABLED": "true",
        "MCP_AUTH_ENABLED": "true",
        "MCP_AUTH_PROVIDER": "github",
        "MCP_GITHUB_CLIENT_ID": "",
        "MCP_GITHUB_CLIENT_SECRET": "",
        "MCP_ALLOWED_IDENTITIES": "",
    }


