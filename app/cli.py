def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if getattr(args, "func", None) is None:
        parser.print_help()
        return 0
    if args.command == "admin" and args.action in ("create", "reset-password") and not args.email:
        parser.error(f"admin {args.action} requires --email")
    try:
        return int(args.func(args))
    except KeyboardInterrupt:
        say()
        say(dim("stopped"))
        return 130
    except Exception as exc:  # noqa: BLE001 - the CLI reports, it does not traceback
        if os.environ.get("NIMKM_DEBUG"):
            raise
        fail(f"{type(exc).__name__}: {exc}")
        say(dim("run with NIMKM_DEBUG=1 for the full traceback, or 'nimkm doctor'"))
        return 1


